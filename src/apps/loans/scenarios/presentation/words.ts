// Croatian addresses the reader as vi, written lowercase inside a sentence. A bank loan is kredit. Scenarios sets offers of both
// repayment types side by side, so its instalment is rata (1 rata, 2 rate, 5 rata). An offer's own dialog takes the words of its type.
// An extra payment is prijevremena otplata, a scenario scenarij and a move to another bank prelazak u drugu banku.
// A name the reader typed cannot be inflected, so it stands in „…” quotes.
// A Croatian day or month, such as 20. 3. 2029. or ožujak 2048., ends with its own full stop, so a sentence that ends on one adds none.

type ChangeKind = 'extra-payment' | 'regular-extra-payment' | 'rate-change' | 'move' | 'term-change'

